const assert=require('node:assert/strict');
const view=require('../dist/graph-view.js');
const article=(id,p)=>({id,title:id,source:{provider:p},symbols:[]});
const edge=(a,b)=>({id:a+':'+b,source:a,target:b,type:'shared_entity',evidence:[]});
const payload={source_graphs:{google:{articles:[article('a','google'),article('b','google')],relations:[edge('a','b')]},yahoo:{articles:[article('c','yahoo')],relations:[]},massive:{articles:[article('d','massive'),article('e','massive')],relations:[edge('d','e')]}},relations:[edge('a','d')]};
let result=view.select(payload,['google'],true);
assert.equal(result.articles.length,2);assert.equal(result.relations.length,1);assert.equal(result.relations[0].source,'google::a');
result=view.select(payload,['google','massive'],false);assert.equal(result.relations.length,3);
result=view.select(payload,['google','massive'],true);assert.equal(result.relations.length,2);
assert.equal(view.select(payload,[],true).articles.length,0);
const snapshot=view.snapshot(payload,result,['google','massive'],true,{query:'news'});
assert.deepEqual(Object.keys(snapshot.source_graphs),['google','massive']);assert.equal(snapshot.cross_relations.length,0);assert.equal(snapshot.source_graphs.google.relations[0].source,'a');
const restored=view.select(snapshot,snapshot.view.sources,true);
assert.deepEqual(restored.relations,result.relations);
const shared={source_graphs:{google:{articles:[article('a','google')],relations:[]},massive:{articles:[article('a','massive')],relations:[]}}};
assert.equal(view.select(shared,['google','massive'],true).articles.length,2);
assert.deepEqual(view.select(shared,['google','massive'],false).articles[0].display_sources,['google','massive']);
assert.equal(view.select(shared,['massive'],false).articles[0].display_provider,'massive');
console.log('PASS: source filters, separate graphs, provenance, empty selection and exact snapshot restoration');
const both=view.select(payload,['google','massive']);
assert(both.relations.some(e=>e.scope==='cross'),'Mixed cross graph is default');
const before=view.select(payload,['google'],false).relations.find(e=>e.scope==='google');
assert.deepEqual(before.raw_relation,both.relations.find(e=>e.scope==='google').raw_relation,'Mixing preserves source relation evidence and weights');
assert.equal(view.linkStyle(before,67).distance,67);
assert(view.linkStyle({scope:'cross',type:'shared_entity'}).strength<view.linkStyle(before).strength);
const scoped={...payload,cross_relations:[{...edge('a','d'),cross_sources:['google','massive']}]};
assert(!view.select(scoped,['google'],false).relations.some(e=>e.scope==='cross'));
console.log('PASS: default mixing, source relationship preservation and weaker cross-source forces');

const dated=(prefix,count,p)=>Array.from({length:count},(_,i)=>({...article(prefix+i,p),published_at:i===count-1?'2025-11-03T00:00:00Z':'2026-10-01T00:00:00Z'}));
const annual={source_graphs:{google:{articles:dated('g',800,'google'),relations:[]},massive:{articles:dated('m',800,'massive'),relations:[]}}};
const sampled=view.select(annual,['google','massive']);
assert.equal(sampled.articles.length,1600);
for(const p of ['google','massive'])assert(sampled.articles.some(a=>a.display_provider===p&&a.published_at.startsWith('2025')),'all source articles retained across years');
console.log('PASS: all 1600 articles retained across both years and sources');

// Display thresholds must not remove the stored raw edge or its evidence.
const hidden=view.select(payload,['google'],false);hidden.relations=[];
const unfiltered=view.snapshot(payload,hidden,['google'],false,{});
assert.equal(unfiltered.source_graphs.google.relations.length,1);
